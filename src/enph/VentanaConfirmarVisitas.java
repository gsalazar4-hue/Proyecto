    public VentanaConfirmarVisitas() {
        initComponents();
        Nav.configurar(this, "ENPH - Confirmar visitas realizadas", 1120, 740);
        Nav.enlazarEncabezado(this, lnkVisita, lnkHogar, lnkSalir);

        List<Datos.Hogar> lista = new ArrayList<>();
        DefaultTableModel m = (DefaultTableModel) tabla.getModel();
        for (Datos.Hogar h : Datos.pendientesDelDia()) {
            if (!Datos.estadoMostrado(h).equals("En visita")) continue;
            lista.add(h);
            m.addRow(new Object[]{hogarHtml(h), h.direccion, h.barrio, Datos.dia(h), "En visita", false});
        }
        estilizar(tabla, spTabla, new int[]{240, 270, 170, 110, 130, 100});

        btnConfirmar.addActionListener(e -> {
            if (tabla.isEditing()) tabla.getCellEditor().stopCellEditing();
            StringBuilder sinVisita = new StringBuilder();
            for (int i = 0; i < lista.size(); i++) {
                Datos.Hogar h = lista.get(i);
                if (Boolean.TRUE.equals(m.getValueAt(i, 5)) && !Datos.visitaRegistradaHoy(h)) {
                    sinVisita.append(sinVisita.length() == 0 ? "" : ", ").append(h.codigo);
                }
            }
            if (sinVisita.length() > 0) {
                mensaje("No tienen la visita registrada: " + sinVisita + ".\n"
                        + "Regístrela desde el dispositivo del jefe de hogar con la opción «Registrar Visita».");
                return;
            }
            // Los hogares marcados quedan Realizada; los no marcados vuelven a Pendiente
            for (int i = 0; i < lista.size(); i++) {
                Datos.setEstadoVisita(lista.get(i), Boolean.TRUE.equals(m.getValueAt(i, 5)) ? "Realizada" : "Pendiente");
            }
            Datos.guardar();
            ir(new VentanaVisitas());
        });
        btnCancelar.addActionListener(e -> ir(new VentanaVisitas()));
    }

