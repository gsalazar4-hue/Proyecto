    public VentanaAsignados() {
        initComponents();
        Nav.configurar(this, "ENPH - Hogares asignados", 1120, 740);
        Nav.enlazarEncabezado(this, lnkVisita, lnkHogar, lnkSalir);

        lblFecha.setText(Datos.HOY.format(Datos.FECHA_LARGA_DEL));
        List<Datos.Hogar> lista = Datos.asignadosOrdenados();
        DefaultTableModel m = (DefaultTableModel) tabla.getModel();
        for (Datos.Hogar h : lista) {
            m.addRow(new Object[]{h.codigo, "<html><center>" + esc(h.direccion) + "<br>" + esc(h.barrio) + "</center></html>",
                    h.jefe, Datos.dia(h) + " de " + Datos.DIAS_ENCUESTA, h.finalizado ? "Finalizado" : "En recolección", ">"});
        }
        estilizar(tabla, spTabla, new int[]{90, 300, 220, 110, 150, 50});
        alClic(tabla, (fila, col, veces) -> {
            if (col == 5 || veces == 2) {
                Datos.hogar = lista.get(fila);
                ir(new VentanaInfoHogar());
            }
        });
    }

