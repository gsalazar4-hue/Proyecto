    public VentanaHistorial(Rol rol) {
        initComponents();
        Nav.configurar(this, "ENPH - Historial de gastos", 1120, 740);
        Nav.enlazarEncabezado(this, lnkVisita, lnkHogar, lnkSalir);
        Datos.Hogar h = Datos.hogar;
        List<Integer> dias = new ArrayList<>(h.diasConGastos());

        DefaultTableModel m = (DefaultTableModel) tabla.getModel();
        for (int d : dias) {
            m.addRow(new Object[]{"Día " + d, Datos.fechaDelDia(d).format(Datos.FECHA_CORTA), h.gastosDelDia(d).size(),
                    h.diasRevisados.contains(d) ? "Revisado" : "Pendiente", ">"});
        }
        estilizar(tabla, spTabla, new int[]{110, 160, 190, 190, 60});
        alClic(tabla, (fila, col, veces) -> ir(new VentanaGastosDia(rol, dias.get(fila), null)));

        btnVolver.addActionListener(e -> ir(rol == Rol.JEFE ? new VentanaJefe() : new VentanaInfoHogar()));
        Nav.aplicarRol(rol, panelRaiz, pnlEncabezado, pnlEnlaces, lblUsuario, lblRolUsuario, pnlCuerpo);
    }


