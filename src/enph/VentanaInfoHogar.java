    private void cerrarEncuesta() {
        Datos.Hogar h = Datos.hogar;
        if (h.finalizado || Datos.dia() != Datos.DIAS_ENCUESTA) {
            mensaje("La encuesta solo se puede cerrar en el día 14 de 14.");
            return;
        }
        if (!Datos.todosLosDiasRevisados()) {
            mensaje("Hay días con gastos pendientes de revisión.\nRevíselos en «Revisar gastos» antes de cerrar la encuesta.");
            return;
        }
        h.finalizado = true;
        Datos.guardar();
        mensaje("La encuesta del hogar " + h.codigo + " quedó en estado Finalizado.");
        ir(new VentanaInfoHogar());
    }

