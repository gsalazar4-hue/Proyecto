    public VentanaRegistrarVisita() {
        initComponents();
        Nav.configurar(this, "ENPH - Registrar visita", 1120, 740);
        Nav.datosJefe(lblUsuario, lblRolUsuario);
        Datos.Hogar h = Datos.hogar;

        tfNumero.setText(String.valueOf(h.visitas.size() + 1));       // diligenciados automáticamente
        tfFecha.setText(Datos.HOY.format(Datos.FECHA_CORTA));
        tfInicio.setText("09:15");
        tfFin.setText("10:00");

        btnGuardar.addActionListener(e -> {
            LocalTime ini, fn;
            try {
                ini = LocalTime.parse(tfInicio.getText().trim(), DateTimeFormatter.ofPattern("H:mm"));
                fn = LocalTime.parse(tfFin.getText().trim(), DateTimeFormatter.ofPattern("H:mm"));
            } catch (DateTimeParseException ex) {
                mensaje("Escriba las horas con el formato HH:mm (por ejemplo 09:15).");
                return;
            }
            if (!fn.isAfter(ini)) {
                mensaje("La hora de fin debe ser posterior a la hora de inicio.");
                return;
            }
            h.visitas.add(new Datos.Visita(h.visitas.size() + 1, Datos.HOY, ini, fn));
            Datos.guardar();
            ir(new VentanaJefe());
        });
        btnCancelar.addActionListener(e -> ir(new VentanaJefe()));
        btnVolver.addActionListener(e -> ir(new VentanaJefe()));
    }


