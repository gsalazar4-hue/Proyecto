    public VentanaGastos() {
        initComponents();
        Nav.configurar(this, "ENPH - Registrar gastos diarios", 1120, 740);
        Nav.datosJefe(lblUsuario, lblRolUsuario);
        Datos.Hogar h = Datos.hogar;
        int dia = Datos.dia();
        List<Datos.Gasto> gs = h.gastosDelDia(dia);

        lblDia.setText("Día de la encuesta: " + dia + "/" + Datos.DIAS_ENCUESTA);
        lblFecha.setText("Fecha: " + Datos.fechaDelDia(dia).format(Datos.FECHA_LARGA_DEL));

        // Sin gastos se muestra el recuadro vacío; con gastos, la tabla
        if (gs.isEmpty()) encabezadoVacio();
        pnlVacio.setVisible(gs.isEmpty());
        spTabla.setVisible(!gs.isEmpty());
        if (!gs.isEmpty()) {
            DefaultTableModel m = (DefaultTableModel) tabla.getModel();
            for (Datos.Gasto g : gs) m.addRow(new Object[]{g.orden, g.alimento, Datos.cantidadTxt(g), Datos.fmt(g.valor), g.tipo});
            estilizar(tabla, spTabla, new int[]{50, 220, 200, 120, 170});
        }

        btnAgregar.addActionListener(e ->
                ir(new VentanaFormularioGasto(Rol.JEFE, null, () -> new VentanaGastos(), () -> new VentanaGastos())));
        btnSalir.addActionListener(e -> ir(new VentanaJefe()));
    }


    /** Recuadro vacío del prototipo: encabezado de la tabla y el mensaje de que aún no hay gastos. */
    private void encabezadoVacio() {
        String[] cols = {"No.", "Alimento o Bebida", "Cantidad", "<html><center>Unidad de<br>medida</center></html>",
                "Valor", "Tipo de gasto"};
        JPanel enc = new JPanel(new GridLayout(1, cols.length));
        enc.setBackground(GRIS_ENC);
        enc.setBorder(new MatteBorder(0, 0, 2, 0, GRIS_BORDE));
        enc.setPreferredSize(new Dimension(10, 54));
        for (String c : cols) {
            JLabel l = new JLabel(c, SwingConstants.CENTER);
            l.setFont(fuente(Font.BOLD, 13));
            l.setForeground(GRIS_TXT);
            enc.add(l);
        }
        pnlVacio.removeAll();
        pnlVacio.setLayout(new BorderLayout());
        pnlVacio.setPreferredSize(new Dimension(100, 120));
        pnlVacio.add(enc, BorderLayout.NORTH);
        lblVacio.setHorizontalAlignment(SwingConstants.CENTER);
        pnlVacio.add(lblVacio, BorderLayout.CENTER);
    }

