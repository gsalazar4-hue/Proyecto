    public VentanaVisitas() {
        initComponents();
        Nav.configurar(this, "ENPH - Hogares pendientes del día", 1120, 740);
        Nav.enlazarEncabezado(this, lnkVisita, lnkHogar, lnkSalir);

        lblFecha.setText(Datos.HOY.format(Datos.FECHA_LARGA));
        List<Datos.Hogar> lista = Datos.pendientesDelDia();
        DefaultTableModel m = (DefaultTableModel) tabla.getModel();
        int n = 1;
        boolean hayEnVisita = false, hayPendiente = false;
        for (Datos.Hogar h : lista) {
            String estado = Datos.estadoMostrado(h);
            hayEnVisita |= estado.equals("En visita");
            hayPendiente |= estado.equals("Pendiente");
            m.addRow(new Object[]{n++, hogarHtml(h), h.direccion, h.barrio, Datos.dia(h), estado, ">"});
        }
        estilizar(tabla, spTabla, new int[]{50, 240, 270, 170, 110, 130, 50});
        alClic(tabla, (fila, col, veces) -> {
            if (col == 6 || veces == 2) {
                Datos.hogar = lista.get(fila);
                ir(new VentanaInfoHogar());
            }
        });

        // Flujo del prototipo: seleccionar hogares -> "En visita" -> confirmar visitas realizadas
        if (hayEnVisita) {
            btnPrincipal.setText("Finalizar visitas");
            btnPrincipal.addActionListener(e -> ir(new VentanaConfirmarVisitas()));
        } else {
            btnPrincipal.setText("Realizar Visita");
            btnPrincipal.setEnabled(hayPendiente);
            btnPrincipal.addActionListener(e -> ir(new VentanaSeleccionVisitas()));
        }

        // Cambia el hogar seleccionado de Pendiente a Realizada y de Realizada a Pendiente
        btnCambiar.setEnabled(!lista.isEmpty());
        btnCambiar.addActionListener(e -> {
            int fila = tabla.getSelectedRow();
            if (fila < 0) {
                mensaje("Seleccione un hogar de la tabla para cambiar su estado.");
                return;
            }
            Datos.Hogar h = lista.get(fila);
            Datos.setEstadoVisita(h, Datos.estadoMostrado(h).equals("Realizada") ? "Pendiente" : "Realizada");
            Datos.guardar();
            ir(new VentanaVisitas());
        });
    }


